def write_stats_csv(results):
    os.makedirs(REPORTS_DIR, exist_ok=True)
    rows = []
    fieldnames = ["analysis", "judge", "group", "n", "metric", "value", "sd",
                  "t_stat", "df", "significance", "cohens_d", "effect", "region"]

    # Per-judge self-preference
    for jid, bias in results["judge_bias"].items():
        if not bias:
            continue
        rows.append({
            "analysis": "ingroup_self_preference",
            "judge": MODEL_DISPLAY.get(jid, jid),
            "group": MODEL_DISPLAY.get(jid, jid),
            "n": bias["in_n"],
            "metric": "axis2_ingroup_vs_outgroup_diff",
            "value": round(bias["diff"], 4),
            "sd": round(bias["in_sd"], 4),
            "t_stat": round(bias["t_stat"], 4),
            "df": round(bias["df"], 1),
            "significance": bias["significance"],
            "cohens_d": round(bias.get("cohens_d", float("nan")), 4),
            "effect": bias["effect_label"],
            "region": REGION.get(jid, "?"),
        })

    # Per-model gap vs Gemini, per cross-val judge
    for judge_id, model_gaps in results["per_model_gap"].items():
        for mid, d in model_gaps.items():
            rows.append({
                "analysis": "per_model_bias_gap",
                "judge": MODEL_DISPLAY.get(judge_id, judge_id),
                "group": d["display"],
                "n": d["n"],
                "metric": "axis2_gap_gemini_minus_judge",
                "value": round(d["mean_gap"], 4),
                "sd": round(d["sd_gap"], 4),
                "t_stat": round(d["t_stat"], 4),
                "df": round(d["df"], 1),
                "significance": d["significance"],
                "cohens_d": round(d["cohens_d"], 4),
                "effect": d["effect_label"],
                "region": REGION.get(mid, "?"),
            })

    # All-axes gap (primary crossval)
    for ax, d in results["all_axes_gap"].items():
        rows.append({
            "analysis": "all_axes_gap",
            "judge": MODEL_DISPLAY.get(results["primary_crossval"], results["primary_crossval"]),
            "group": ax,
            "n": d["n"],
            "metric": "mean_gap_gemini_minus_judge",
            "value": round(d["mean_gap"], 4),
            "sd": round(d["sd_gap"], 4),
            "t_stat": round(d["t_stat"], 4),
            "df": round(d["df"], 1),
            "significance": d["significance"],
            "cohens_d": "",
            "effect": "",
            "region": "",
        })

    with open(OUTPUT_CSV, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
    print(f"  Stats CSV saved: {OUTPUT_CSV}")



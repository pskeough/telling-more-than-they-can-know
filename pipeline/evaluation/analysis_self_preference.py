def run_analysis():
    # Detect which crossval CSVs are present
    available_judges = {}
    for judge_id, csv_path in CROSSVAL_JUDGES.items():
        if os.path.exists(csv_path) and os.stat(csv_path).st_size > 0:
            available_judges[judge_id] = csv_path
        else:
            print(f"  Skipping {MODEL_DISPLAY.get(judge_id, judge_id)}: file not found ({os.path.basename(csv_path)})")

    if not available_judges:
        print("ERROR: No crossval judge CSVs found. Run run_additional_judges.py first.")
        sys.exit(1)

    print(f"  Judges available: {[MODEL_DISPLAY.get(j, j) for j in available_judges]}")

    # Load primary (Gemini) evaluations
    primary = {r["explanation_id"]: r for r in load_csv(PRIMARY_CSV)}

    # Load all crossval judges; find common overlap across all
    crossval_data = {}
    for judge_id, csv_path in available_judges.items():
        crossval_data[judge_id] = {r["explanation_id"]: r for r in load_csv(csv_path)}

    # Overlap = IDs present in primary AND all available crossval judges
    overlap = set(primary.keys())
    for judge_rows in crossval_data.values():
        overlap &= set(judge_rows.keys())
    overlap = sorted(overlap)
    n = len(overlap)
    print(f"  Common overlap across all judges: {n} explanations\n")

    axes = ["axis1", "axis2", "axis3", "axis4"]
    judge_ids = list(available_judges.keys())  # ordered list

    # Build unified records: one per explanation, scores keyed by judge_id
    records = []
    for eid in overlap:
        p = primary[eid]
        rec = {
            "explanation_id": eid,
            "model": p["model"],
            "explanation_type": p["explanation_type"],
            "cohort_id": p["cohort_id"],
            "region": REGION.get(p["model"], "Unknown"),
            # Gemini (primary) scores
            "gemini": {ax: safe_float(p.get(f"{ax}_consensus")) for ax in axes},
        }
        for judge_id in judge_ids:
            cv = crossval_data[judge_id][eid]
            rec[judge_id] = {ax: safe_float(cv.get(f"{ax}_consensus")) for ax in axes}
        records.append(rec)

    # -----------------------------------------------------------------------
    # 1. Cross-judge agreement: Gemini vs each crossval judge (Spearman, MAD)
    # -----------------------------------------------------------------------
    print("--- 1. Cross-Judge Agreement (Gemini vs each judge) ---")
    agreement = {}  # judge_id -> axis -> stats
    for judge_id in judge_ids:
        disp = MODEL_DISPLAY.get(judge_id, judge_id)
        agreement[judge_id] = {}
        print(f"\n  vs {disp}:")
        for ax in axes:
            pairs = [(r["gemini"][ax], r[judge_id][ax]) for r in records
                     if r["gemini"][ax] is not None and r[judge_id][ax] is not None]
            if len(pairs) < 3:
                continue
            gv = [p[0] for p in pairs]
            jv = [p[1] for p in pairs]
            rho, t_stat = spearman(gv, jv)
            mad   = float(np.mean(np.abs(np.array(gv) - np.array(jv))))
            exact = float(np.mean(np.round(np.array(gv)) == np.round(np.array(jv))))
            gap   = float(np.mean(gv)) - float(np.mean(jv))
            agreement[judge_id][ax] = {
                "n": len(pairs), "rho": rho, "t_stat": t_stat,
                "significance": p_label(abs(t_stat), len(pairs) - 2),
                "mad": mad, "exact_agreement": exact,
                "gemini_mean": float(np.mean(gv)), "judge_mean": float(np.mean(jv)),
                "mean_gap": gap,
            }
            print(f"    {ax}: rho={rho:.3f} ({p_label(abs(t_stat), len(pairs)-2)})  "
                  f"MAD={mad:.3f}  exact={exact:.1%}  gap={gap:+.3f}")

    # -----------------------------------------------------------------------
    # 2. Per-judge self-preference: in-group vs out-group (axis 2)
    # -----------------------------------------------------------------------
    print("\n--- 2. Self-Preference Bias per Judge (Axis 2 Faithfulness) ---")

    def ingroup_stats(inv, outv, name):
        if not inv or not outv:
            return None
        t, df, d = welch_t_and_d(inv, outv)
        sig = p_label(abs(t), df)
        print(f"\n  {name} (in={len(inv)}, out={len(outv)}):")
        print(f"    In-group:  mean={np.mean(inv):.3f}  sd={np.std(inv, ddof=1):.3f}")
        print(f"    Out-group: mean={np.mean(outv):.3f}  sd={np.std(outv, ddof=1):.3f}")
        print(f"    Diff={np.mean(inv)-np.mean(outv):+.3f}  t({df:.0f})={t:.3f}  {sig}  d={d:.3f} ({effect_label(d)})")
        return {
            "in_mean": float(np.mean(inv)), "in_sd": float(np.std(inv, ddof=1)), "in_n": len(inv),
            "out_mean": float(np.mean(outv)), "out_sd": float(np.std(outv, ddof=1)), "out_n": len(outv),
            "diff": float(np.mean(inv) - np.mean(outv)),
            "t_stat": t, "df": df, "significance": sig,
            "cohens_d": d, "effect_label": effect_label(d),
        }

    # Gemini judge (primary) self-preference
    g_in  = [r["gemini"]["axis2"] for r in records
             if r["model"] == GEMINI_ID and r["gemini"]["axis2"] is not None]
    g_out = [r["gemini"]["axis2"] for r in records
             if r["model"] != GEMINI_ID and r["gemini"]["axis2"] is not None]
    judge_bias = {"google/gemini-3-flash-preview": ingroup_stats(g_in, g_out, "Gemini (primary judge)")}

    # Each crossval judge self-preference
    for judge_id in judge_ids:
        disp = MODEL_DISPLAY.get(judge_id, judge_id)
        j_in  = [r[judge_id]["axis2"] for r in records
                 if r["model"] == judge_id and r[judge_id]["axis2"] is not None]
        j_out = [r[judge_id]["axis2"] for r in records
                 if r["model"] != judge_id and r[judge_id]["axis2"] is not None]
        judge_bias[judge_id] = ingroup_stats(j_in, j_out, f"{disp} (crossval judge)")

    # -----------------------------------------------------------------------
    # 3. Per-model bias gap vs Gemini (axis 2), for each available judge
    # -----------------------------------------------------------------------
    print("\n--- 3. Per-Model Bias Gap vs Gemini Primary (Axis 2) ---")
    per_model_gap = {}  # judge_id -> model_id -> stats
    for judge_id in judge_ids:
        disp_j = MODEL_DISPLAY.get(judge_id, judge_id)
        per_model_gap[judge_id] = {}
        print(f"\n  Judge: {disp_j}")
        for model_id in sorted(set(r["model"] for r in records)):
            gvals = [r["gemini"]["axis2"] for r in records
                     if r["model"] == model_id and r["gemini"]["axis2"] is not None]
            jvals = [r[judge_id]["axis2"] for r in records
                     if r["model"] == model_id and r[judge_id]["axis2"] is not None]
            if not gvals or not jvals:
                continue
            diffs = [g - j for g, j in zip(gvals, jvals)]
            t, df = paired_t(diffs)
            _, _, cohed = welch_t_and_d(gvals, jvals)
            disp_m = MODEL_DISPLAY.get(model_id, model_id)
            per_model_gap[judge_id][model_id] = {
                "display": disp_m,
                "n": len(diffs),
                "gemini_mean": float(np.mean(gvals)),
                "judge_mean": float(np.mean(jvals)),
                "mean_gap": float(np.mean(diffs)),
                "sd_gap": float(np.std(diffs, ddof=1)),
                "t_stat": t, "df": df,
                "significance": p_label(abs(t), df),
                "cohens_d": cohed,
                "effect_label": effect_label(cohed),
            }
            print(f"    {disp_m:20s}: Gemini={np.mean(gvals):.3f}  {disp_j}={np.mean(jvals):.3f}  "
                  f"gap={np.mean(diffs):+.3f}  d={cohed:.3f} ({effect_label(cohed)})  "
                  f"{p_label(abs(t), df)}")

    # -----------------------------------------------------------------------
    # 4. Bias gap across all axes (Gemini vs DeepSeek, primary crossval)
    # -----------------------------------------------------------------------
    primary_crossval = judge_ids[0]  # DeepSeek is always first
    print(f"\n--- 4. Bias Gap Across All Axes (Gemini vs {MODEL_DISPLAY.get(primary_crossval)}) ---")
    all_axes_gap = {}
    for ax in axes:
        diffs = [r["gemini"][ax] - r[primary_crossval][ax] for r in records
                 if r["gemini"][ax] is not None and r[primary_crossval][ax] is not None]
        if not diffs:
            continue
        t, df = paired_t(diffs)
        all_axes_gap[ax] = {
            "n": len(diffs),
            "mean_gap": float(np.mean(diffs)),
            "sd_gap": float(np.std(diffs, ddof=1)),
            "t_stat": t, "df": df,
            "significance": p_label(abs(t), df),
        }
        print(f"  {ax}: gap={np.mean(diffs):+.3f}  sd={np.std(diffs, ddof=1):.3f}  "
              f"t({df:.0f})={t:.3f}  {p_label(abs(t), df)}")

    # -----------------------------------------------------------------------
    # 5. Self-preference by explanation type (Gemini judge, axis 2)
    # -----------------------------------------------------------------------
    print("\n--- 5. Gemini Self-Preference by Explanation Type ---")
    type_breakdown = {}
    for exp_type in ["abductive", "contrastive", "counterfactual", "feature_attribution"]:
        tr = [r for r in records if r["explanation_type"] == exp_type]
        g_in_t  = [r["gemini"]["axis2"] for r in tr
                   if r["model"] == GEMINI_ID and r["gemini"]["axis2"] is not None]
        g_out_t = [r["gemini"]["axis2"] for r in tr
                   if r["model"] != GEMINI_ID and r["gemini"]["axis2"] is not None]
        if not g_in_t or not g_out_t:
            continue
        t, df, d = welch_t_and_d(g_in_t, g_out_t)
        type_breakdown[exp_type] = {
            "in_mean": float(np.mean(g_in_t)), "out_mean": float(np.mean(g_out_t)),
            "in_n": len(g_in_t), "out_n": len(g_out_t),
            "diff": float(np.mean(g_in_t) - np.mean(g_out_t)),
            "t_stat": t, "df": df,
            "significance": p_label(abs(t), df),
            "cohens_d": d, "effect_label": effect_label(d),
        }
        print(f"  {exp_type:22s}: in={np.mean(g_in_t):.3f}  out={np.mean(g_out_t):.3f}  "
              f"gap={np.mean(g_in_t)-np.mean(g_out_t):+.3f}  d={d:.3f} ({effect_label(d)})")

    # -----------------------------------------------------------------------
    # 6. East vs West regional grouping (if multiple judges available)
    # -----------------------------------------------------------------------
    print("\n--- 6. East vs West Regional Self-Preference ---")
    region_bias = {}
    for region in ["Western", "Eastern"]:
        region_judge_ids = [jid for jid in judge_ids if REGION.get(jid) == region]
        region_judge_ids_with_gemini = (
            [GEMINI_ID] if REGION.get(GEMINI_ID) == region else []
        ) + region_judge_ids

        if not region_judge_ids_with_gemini:
            continue

        # For each judge in this region, compute self-preference d
        d_values = []
        for jid in region_judge_ids_with_gemini:
            bias = judge_bias.get(jid)
            if bias and not math.isnan(bias.get("cohens_d", float("nan"))):
                d_values.append(bias["cohens_d"])

        if not d_values:
            continue

        region_bias[region] = {
            "judges": [MODEL_DISPLAY.get(j, j) for j in region_judge_ids_with_gemini],
            "mean_d": float(np.mean(d_values)),
            "individual_d": d_values,
        }
        print(f"  {region}: judges={[MODEL_DISPLAY.get(j,j) for j in region_judge_ids_with_gemini]}  "
              f"mean_d={np.mean(d_values):.3f}  individual_d={[round(d,3) for d in d_values]}")

    if len(region_bias) == 2:
        west_ds = region_bias.get("Western", {}).get("individual_d", [])
        east_ds = region_bias.get("Eastern", {}).get("individual_d", [])
        if west_ds and east_ds:
            t_reg, df_reg, d_reg = welch_t_and_d(west_ds, east_ds)
            region_bias["comparison"] = {
                "t_stat": t_reg, "df": df_reg,
                "significance": p_label(abs(t_reg), df_reg),
                "cohens_d": d_reg, "effect_label": effect_label(d_reg),
            }
            print(f"  West vs East: t({df_reg:.0f})={t_reg:.3f}  "
                  f"{p_label(abs(t_reg), df_reg)}  d={d_reg:.3f} ({effect_label(d_reg)})")
        else:
            print("  (Insufficient judges per region for statistical comparison — run additional judges first)")

    return {
        "n_overlap": n, "records": records,
        "judge_ids": judge_ids,
        "available_judges": available_judges,
        "agreement": agreement,
        "judge_bias": judge_bias,
        "per_model_gap": per_model_gap,
        "all_axes_gap": all_axes_gap,
        "type_breakdown": type_breakdown,
        "region_bias": region_bias,
        "primary_crossval": primary_crossval,
    }


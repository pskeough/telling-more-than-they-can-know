def welch_t_and_d(a, b):
    """Welch's t-statistic + Satterthwaite df + Cohen's d (pooled SD)."""
    a, b = np.array(a, dtype=float), np.array(b, dtype=float)
    n1, n2 = len(a), len(b)
    if n1 < 2 or n2 < 2:
        return float("nan"), float("nan"), float("nan")
    m1, m2 = np.mean(a), np.mean(b)
    v1, v2 = np.var(a, ddof=1), np.var(b, ddof=1)
    se = math.sqrt(v1 / n1 + v2 / n2)
    if se == 0:
        return 0.0, float("nan"), 0.0
    t = (m1 - m2) / se
    # Welch-Satterthwaite df
    num = (v1 / n1 + v2 / n2) ** 2
    den = (v1 / n1) ** 2 / (n1 - 1) + (v2 / n2) ** 2 / (n2 - 1)
    df = num / den if den > 0 else float("nan")
    # Cohen's d pooled
    sp = math.sqrt(((n1 - 1) * v1 + (n2 - 1) * v2) / (n1 + n2 - 2))
    d = (m1 - m2) / sp if sp > 0 else float("nan")
    return t, df, d

def paired_t(diffs):
    diffs = np.array(diffs, dtype=float)
    n = len(diffs)
    if n < 2:
        return float("nan"), float("nan")
    m = np.mean(diffs)
    s = np.std(diffs, ddof=1)
    if s == 0:
        return float("nan"), n - 1
    return m / (s / math.sqrt(n)), float(n - 1)

def spearman(x, y):
    x, y = np.array(x, dtype=float), np.array(y, dtype=float)
    n = len(x)
    if n < 3:
        return float("nan"), float("nan")
    # Rank transform
    def rank(v):
        idx = np.argsort(np.argsort(v))
        return idx.astype(float) + 1
    rx, ry = rank(x), rank(y)
    d2 = np.sum((rx - ry) ** 2)
    rho = 1.0 - 6.0 * d2 / (n * (n ** 2 - 1))
    t_stat = rho * math.sqrt((n - 2) / max(1 - rho ** 2, 1e-12))
    return float(rho), float(t_stat)

def p_label(t_abs, df=60):
    """Significance label from |t| using standard critical values."""
    if math.isnan(t_abs):
        return "n/a"
    # Use df=30 as conservative lower bound for df >= 30
    eff_df = max(df, 30) if not math.isnan(df) else 30
    thresholds = [(3.646, "p < .001"), (2.750, "p < .01"), (2.042, "p < .05")]
    for thresh, label in thresholds:
        if t_abs > thresh:
            return label
    return "ns"

def effect_label(d):
    if math.isnan(d):
        return "n/a"
    a = abs(d)
    if a < 0.2:
        return "negligible"
    elif a < 0.5:
        return "small"
    elif a < 0.8:
        return "medium"
    else:
        return "large"

